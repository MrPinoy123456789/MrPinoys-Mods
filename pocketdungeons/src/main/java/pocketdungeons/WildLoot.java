package pocketdungeons;

/**
 * Wild dungeons pay war supplies (owner, 2026-11-02): gold, golden apples, iron, emeralds and nether wart, the things
 * kingdoms need for war, in place of the campaign's pocket run tables (bread, cobblestone, planks, raw diamonds and
 * netherite). A wild floor resolves every chest, supply chest, vault and reward barrel table with this suffix
 * ({@code chests/tier_2_wild}, {@code vaults/tier_3_ominous_wild}, {@code chests/supply_tier_1_wild}); a table that
 * does not exist falls back to the base table as any suffix does. A theme's own suffix and loot table override do not
 * apply on a wild floor. The tables are generated by {@code tools/gen_wild_loot.py}.
 */
final class WildLoot {

    static final String SUFFIX = "_wild";

    private WildLoot() {}

    /** The loot suffix a floor stamps and pays with: the wild suffix on a wild floor, else the theme's. */
    static String suffix(boolean wild, String themeSuffix) {
        return wild ? SUFFIX : themeSuffix;
    }

    /** The theme's loot table override, which a wild floor ignores so its war supply tables always win. */
    static String override(boolean wild, String themeOverride) {
        return wild ? null : themeOverride;
    }
}
