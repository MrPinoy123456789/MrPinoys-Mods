"""Regenerate docs/CODEMAP.md: one line per main class (lines of code and the first sentence of its javadoc).

    python tools/gen_codemap.py        (from pocketdungeons)

The index is meant to be grepped, not read: `grep -n -i "dialog" docs/CODEMAP.md`. The hand-written section at the
top of the file lives in tools/codemap_head.md and is copied in unchanged.
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'main', 'java', 'pocketdungeons')
OUT = os.path.join(ROOT, 'docs', 'CODEMAP.md')
HEAD = os.path.join(ROOT, 'tools', 'codemap_head.md')


def first_sentence(text):
    m = re.search(r'/\*\*(.*?)\*/\s*(?:@\w+(?:\([^)]*\))?\s*)*(?:public |final |abstract |sealed )*(?:class|record|interface|enum)\s+(\w+)', text, re.S)
    if not m:
        return None, ''
    body = re.sub(r'^\s*\*\s?', '', m.group(1), flags=re.M)
    body = re.sub(r'<[^>]+>|\{@\w+\s+([^}]*)\}', r'\1', body)
    body = ' '.join(body.split())
    body = body.replace(chr(92) + 'u0027', chr(39))
    parts = re.split(r'(?<=\.)\s', body)
    sentence = parts[0]
    # A label such as "The Warden whelp (design pass 2026-10-09):" is not a summary: take the next sentence too.
    for more in parts[1:]:
        if len(sentence) >= 70:
            break
        sentence += ' ' + more
    return m.group(2), sentence[:190]


def entry(path, sub=''):
    text = open(path, encoding='utf-8').read()
    name = os.path.splitext(os.path.basename(path))[0]
    cls, summary = first_sentence(text)
    lines = text.count('\n') + 1
    return '- `%s%s` (%d): %s' % (sub, name, lines, summary or '(no class comment)')


def main():
    out = []
    if os.path.exists(HEAD):
        out.append(open(HEAD, encoding='utf-8').read().rstrip('\n'))
        out.append('')
    out.append('## Main classes')
    out.append('')
    out.append('Generated by `tools/gen_codemap.py`: `(N)` is the line count, then the first sentence of the class comment.')
    out.append('')
    for f in sorted(os.listdir(SRC)):
        if f.endswith('.java'):
            out.append(entry(os.path.join(SRC, f)))
    mixins = os.path.join(SRC, 'mixin')
    if os.path.isdir(mixins):
        out.append('')
        out.append('## Mixins (`mixin/`)')
        out.append('')
        for f in sorted(os.listdir(mixins)):
            if f.endswith('.java'):
                out.append(entry(os.path.join(mixins, f), 'mixin/'))
    open(OUT, 'w', encoding='utf-8', newline='').write('\r\n'.join(out) + '\r\n')
    print('wrote', OUT, len(out), 'lines')


if __name__ == '__main__':
    main()
