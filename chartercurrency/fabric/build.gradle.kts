plugins {
    // Version comes from settings.gradle.kts, which reads it from gradle.properties.
    id("net.fabricmc.fabric-loom")
    `java-library`
}

version = "${property("mod_version")}"
group = "${property("maven_group")}"

base {
    archivesName = "chartercurrency"
}

dependencies {
    minecraft("com.mojang:minecraft:${property("minecraft_version")}")
    // No mappings dependency. Minecraft ships unobfuscated with parameter names
    // since 26.1, so there is no deobfuscation step and Yarn is deprecated.
    // Mojang's names ARE the names. Ignore any tutorial written against 1.21 or earlier.

    implementation("net.fabricmc:fabric-loader:${property("loader_version")}")
    implementation("net.fabricmc.fabric-api:fabric-api:${property("fabric_api_version")}")

    // The shop GUI. Vanilla clients see an ordinary chest window. Plain
    // implementation rather than modImplementation: 26.x ships unobfuscated, so the
    // remapping modImplementation performs is a no-op here, and its Kotlin DSL
    // accessor is not generated by Loom in this setup -- same reasoning as ballot
    // and quizengine's sgui dependency.
    implementation("eu.pb4:sgui:2.2.1+26.3")
    include("eu.pb4:sgui:2.2.1+26.3")

    // The economy, shaded into the jar. Server owners drop in one file.
    implementation(project(":core"))
    include(project(":core"))

    // Charter's published api, compile time only. The real classes come from Charter at
    // runtime; the stub module is never shipped (see charter-api-stub/build.gradle.kts).
    compileOnly(project(":charter-api-stub"))
}

repositories {
    mavenLocal()
    maven("https://maven.nucleoid.xyz/") { name = "Nucleoid" }
}

loom {
    // No client source set: this mod is server-side only.
    runs.configureEach {
        if (name == "gameTest") {
            // A JUnit style report of every gametest by name; the server log only prints a count.
            vmArg("-Dfabric-api.gametest.report-file=${layout.buildDirectory.get().asFile}/gametest-report.xml")
            // A fixed, small heap: this machine runs out of commit space with larger ones.
            vmArg("-Xmx1500m")
        }
    }
}

// The gametest harness, as in fortune. The source set carries its own fabric.mod.json (mod id
// chartercurrency-gametest), so nothing test related enters the shipped jar. Every gametest class must be
// listed there or it never runs. The classes sit in the package chartercurrency to reach its package private
// services (coins, the Mint, the shop), the way a test of this mod's own code has to.
fabricApi.configureTests {
    createSourceSet = true
    modId = "chartercurrency-gametest"
    enableGameTests = true
    enableClientGameTests = false
}

// Every gametest run starts from a fresh world and a fresh config.
tasks.matching { it.name == "runGameTest" }.configureEach {
    doFirst {
        delete(layout.buildDirectory.dir("run/gameTest/world"))
        delete(layout.buildDirectory.dir("run/gameTest/config/chartercurrency"))
    }
}

java {
    withSourcesJar()
    sourceCompatibility = JavaVersion.VERSION_25
    targetCompatibility = JavaVersion.VERSION_25
}

tasks.withType<JavaCompile>().configureEach {
    options.release = 25
    options.encoding = "UTF-8"
}

tasks.processResources {
    inputs.property("version", project.version)
    filesMatching("fabric.mod.json") {
        expand("version" to project.version)
    }
}

val distDir = rootProject.projectDir.parentFile.resolve("dist")

tasks.register<Copy>("dist") {
    dependsOn("jar")
    from(layout.buildDirectory.dir("libs"))
    into(distDir)
    exclude("*-sources.jar")
}

tasks.named("build") {
    finalizedBy("dist")
}

